/*
 * ================================================================
 * VFmode.c — V/F 开环控制（Simulink 自动生成 + 手动注释）
 * 
 *   V/F 开环 = 不用传感器，让电机转起来的最简单方法
 *
 * 原理（用一句话说清楚）：
 *   给电机的三相线通入旋转电压 → 产生旋转磁场 → 转子被磁场拖着转
 *   因为我们不知道转子实际在哪里，所以叫"开环"（没有反馈）
 *
 * 你只需要设置 4 个参数：
 *   rtU.ud   = 0     （直轴电压，一般设 0，不用管）
 *   rtU.uq   = 12    （交轴电压，调这个改变力矩大小）
 *   rtU.Freq = 4     （目标频率 Hz，调这个改变转速）
 *   rtU.Vbus = 24    （你的电源电压，一般不变）
 *
 * 然后在 ADC 回调里调 VFmode_step()，它就会算出三个 CCR 值：
 *   rtY.tABC[0] → U 相 → TIM1->CCR3
 *   rtY.tABC[1] → V 相 → TIM1->CCR2
 *   rtY.tABC[2] → W 相 → TIM1->CCR1
 *
 * 注意相序：你的硬件是 CH1=W, CH2=V, CH3=U
 * ================================================================ */

#include "VFmode.h"

/* ===== 全局变量 =====
 * 这些变量定义在 VFmode.h 中（用 extern 声明），定义在这里（分配内存）：
 *   rtDW — 内部状态（比如上次的角度值）
 *   rtU  — 输入（你在外面设好值，模型里面读）
 *   rtY  — 输出（模型算好了，你在外面读）
 */
VF_DW VF_rtDW;
VF_ExtU VF_rtU;
VF_ExtY VF_rtY;

/* ================================================================
 * VFmode_step — V/F 控制核心函数
 *
 * 每次 ADC 回调调用一次（10kHz 约每 0.1ms 一次）。
 * 内部 5 个步骤，每个步骤后面都有中文说明。
 * ================================================================ */
void VFmode_step(void)
{
  /* ---- 临时变量 ----
   * 这些变量只在函数内部用，名字是 Simulink 自动生成的，比较奇怪。
   * 对应关系：
   *   rtb_Sum      = 当前电角度 θ（rad），范围 0~6.283（0~360°）
   *   rtb_Add      = Uα（逆 Park 输出的 α 轴电压）
   *   rtb_Add_a    = Uβ 或 Ub（被重复使用）
   *   rtb_Add1_d   = Uc 临时值
   *   rtb_Min      = 零序注入的中间结果
   */
  real32_T rtb_Add;
  real32_T rtb_Add1_d;
  real32_T rtb_Add_a;
  real32_T rtb_Min;
  real32_T rtb_Sum;

  /* ================================================================
   * 第 1 步：角度积分（让电角度匀速增加）
   * 
   * 公式：新角度 = 步长 × 频率 + 旧角度
   *   0.000628318521 = 2π × 0.0001（2π × 10kHz 周期）
   *   rtU.Freq       = 目标频率（Hz），比如 4Hz
   *   rtDW.UnitDelay_DSTATE = 上一次的角度
   *
   * 效果：每进一次函数，角度增加固定的一小步。
   *   4Hz 时，跑 2500 步（0.25 秒）转一整圈（2π）。
   * ================================================================ */
  rtb_Sum = 0.000628318521F * VF_rtU.Freq + VF_rtDW.UnitDelay_DSTATE;

  /* ================================================================
   * 第 2 步：角度限幅（保证在 0~2π 之间）
   *
   * 角度不能无限大，也不能小于 0。
   *   超过 2π → 减去 2π（转完一圈从头算）
   *   小于 0   → 加上 2π
   * ================================================================ */
  if (rtb_Sum > 6.28318548F) {
    rtb_Sum -= 6.28318548F;
  } else if (rtb_Sum < 0.0F) {
    rtb_Sum += 6.28318548F;
  }

  /* ================================================================
   * 第 3 步：逆 Park 变换（Ud/Uq → Uα/Uβ）
   *
   * 你在外面设了 Ud=0, Uq=12（固定电压）。
   * 但电机需要的是三相电压，不是 dq 电压。
   * 逆 Park 就是用当前角度 θ 把 dq 转成 αβ：
   *   Uα = Ud×cosθ - Uq×sinθ
   *   Uβ = Ud×sinθ + Uq×cosθ
   *
   * 因为 Ud=0，实际上就是：
   *   Uα = -12 × sinθ
   *   Uβ =  12 × cosθ
   * 所以 Uα、Uβ 是两个正余弦波，相差 90°。
   * ================================================================ */

  /* 先算 sinθ 和 cosθ */
  rtb_Add_a = cosf(rtb_Sum);     // cosθ
  rtb_Min = sinf(rtb_Sum);       // sinθ

  /* 逆 Park：Uα = Ud×cosθ - Uq×sinθ */
  rtb_Add = VF_rtU.ud * rtb_Add_a - VF_rtU.uq * rtb_Min;  // ← 这是 Uα

  /* Uβ（用于后面逆 Clark）：Uβ = Ud×sinθ + Uq×cosθ */
  rtb_Min = (VF_rtU.ud * rtb_Min + VF_rtU.uq * rtb_Add_a) * 0.866025388F;

  /* ================================================================
   * 第 4 步：逆 Clark + 零序注入（SVPWM）
   *
   * 逆 Clark：Uα/Uβ → Ua/Ub/Uc（三相电压）
   *   公式：
   *     Ua = Uα
   *     Ub = -0.5×Uα + √3/2×Uβ
   *     Uc = -0.5×Uα - √3/2×Uβ
   *   0.866025388 ≈ √3/2
   *
   * 零序注入（马鞍波）：
   *   找到 Ua/Ub/Uc 的最高和最低值，算出零序分量 V0。
   *   把 V0 加到三相上 → 波峰压低、波谷抬高。
   *   效果：同样母线电压下，电机能跑更高的速度。
   *
   * 转 CCR（给定时器的比较值）：
   *   CCR = (-Vx / Vbus + 0.5) × 8000
   *   8000 是 TIM1 的 ARR（自动重装载值）
   * ================================================================ */

  /* 逆 Clark 第一步：Ua（就是 Uα）*/
  rtb_Add1_d = -0.5F * rtb_Add;          // -0.5 × Uα

  /* 逆 Clark 第二步：Ub = -0.5×Uα + √3/2×Uβ */
  rtb_Add_a = rtb_Add1_d + rtb_Min;      // Uα部分 + Uβ部分 = Ub

  /* 逆 Clark 第三步：Uc = -0.5×Uα - √3/2×Uβ */
  rtb_Add1_d -= rtb_Min;                  // Uα部分 - Uβ部分 = Uc

  /* 零序注入：V0 = -0.5 × (Umax + Umin) */
  rtb_Min = (fminf(fminf(rtb_Add, rtb_Add_a), rtb_Add1_d) +
             fmaxf(fmaxf(rtb_Add, rtb_Add_a), rtb_Add1_d)) * -0.5F;

  /* 把 V0 加到三相上，转成 CCR 值 */
  VF_rtY.tABC[0] = (-(rtb_Min + rtb_Add)     / VF_rtU.Vbus + 0.5F) * 8000.0F;  // Ua → CCR
  VF_rtY.tABC[1] = (-(rtb_Min + rtb_Add_a)   / VF_rtU.Vbus + 0.5F) * 8000.0F;  // Ub → CCR
  VF_rtY.tABC[2] = (-(rtb_Min + rtb_Add1_d)  / VF_rtU.Vbus + 0.5F) * 8000.0F;  // Uc → CCR

  /* ================================================================
   * 保存当前角度（给下一次用）
   * rtDW.UnitDelay_DSTATE 存着角度，下次进函数时加上步长继续走
   * ================================================================ */
  VF_rtDW.UnitDelay_DSTATE = rtb_Sum;
}

