extern HALL_Handle_t HALL_Handle;
/* 定时器输入捕获中断回调函数
 * 触发时机：TIM输入捕获通道检测到电平跳变时进入，用于霍尔传感器边沿捕获
 */
void HAL_TIM_IC_CaptureCallback(TIM_HandleTypeDef *htim)
{
	// 只处理TIM4定时器的捕获中断，其他定时器直接退出
    if (htim->Instance != TIM4)
    {
        return;
    }

    // 判断中断来源：霍尔A/B/C相（通道1/2/3）任意一路产生边沿捕获
    if(htim->Channel == HAL_TIM_ACTIVE_CHANNEL_1 ||
		htim->Channel == HAL_TIM_ACTIVE_CHANNEL_2 ||
		htim->Channel == HAL_TIM_ACTIVE_CHANNEL_3)
    {
        // 步骤1：霍尔解码函数
        // 读取三相霍尔电平查表，计算当前真实电角度、电机转速、电角速度
        HALL_Get_Electrical_Angle(&HALL_Handle);
        
        // 步骤2：用霍尔实测电角度覆盖插值预估角度
        // 修正积分累计角度误差，消除长时间运行带来的角度漂移
        HALL_Handle.HallElAngle = HALL_Handle.MeasuredElAngle;
    }
}

